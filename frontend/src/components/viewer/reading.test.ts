import { describe, expect, it } from "vitest";
import type { TextSegment } from "@/lib/api/types";
import CASES from "./fixtures/reading_cases.json";
import { mapSpanToReading, mapSpansToReading, passageInReading } from "./reading";
import { splitBySpans } from "./textSpans";

// A stored email and the text the agent reads: the Date header is replaced by
// the grant's date (a longer line), the Message-ID header is dropped, and the
// body is kept as it is.
const STORED = [
  "From: robin.example@university.example", // 0..38, newline at 38
  "Date: Sat, 21 Feb 2026 09:12:00 -0800", // 39..76, newline at 76
  "Message-ID: <synthetic-0001@university.example>", // 77..124, newline at 124
  "Subject: Usage statement SEQ-0207", // 125..158
  "",
  "Total: $2,180.00",
].join("\n");

const READING = [
  "From: robin.example@university.example",
  "Date: Tuesday, February 24, 2026 at 00:00 UTC",
  "Subject: Usage statement SEQ-0207",
  "",
  "Total: $2,180.00",
].join("\n");

const fromLen = "From: robin.example@university.example\n".length; // 39
const storedSubject = STORED.indexOf("Subject:");
const readingSubject = READING.indexOf("Subject:");

const SEGMENTS: TextSegment[] = [
  { stored_start: 0, reading_start: 0, length: fromLen },
  { stored_start: storedSubject, reading_start: readingSubject, length: STORED.length - storedSubject },
];

const slice = (text: string, span: { start: number; end: number } | null) => (span ? text.slice(span.start, span.end) : null);

describe("mapSpanToReading", () => {
  it("moves a highlight inside a kept span with the span", () => {
    const start = STORED.indexOf("robin.example");
    const span = mapSpanToReading({ start, end: start + "robin.example".length }, SEGMENTS, READING);
    expect(slice(READING, span)).toBe("robin.example");
  });

  it("shifts a highlight after a header that was replaced by a longer line", () => {
    const start = STORED.indexOf("$2,180.00");
    const span = mapSpanToReading({ start, end: start + "$2,180.00".length }, SEGMENTS, READING);
    expect(span?.start).not.toBe(start);
    expect(slice(READING, span)).toBe("$2,180.00");
  });

  it("runs across a gap, taking in the replaced line between", () => {
    const start = STORED.indexOf("university.example");
    const end = STORED.indexOf("Subject:") + "Subject:".length;
    const span = mapSpanToReading({ start, end }, SEGMENTS, READING);
    expect(slice(READING, span)).toBe("university.example\nDate: Tuesday, February 24, 2026 at 00:00 UTC\nSubject:");
  });

  it("highlights the replaced line for a range that falls in a gap", () => {
    const start = STORED.indexOf("21 Feb 2026");
    const span = mapSpanToReading({ start, end: start + "21 Feb 2026".length }, SEGMENTS, READING);
    expect(slice(READING, span)).toBe("Date: Tuesday, February 24, 2026 at 00:00 UTC");
  });

  it("highlights nothing for a dropped header with no line in its place", () => {
    // Only the From line is kept, and nothing replaces what follows it.
    const dropped: TextSegment[] = [{ stored_start: 0, reading_start: 0, length: fromLen }];
    const reading = STORED.slice(0, fromLen);
    const start = STORED.indexOf("synthetic-0001");
    expect(mapSpanToReading({ start, end: start + 5 }, dropped, reading)).toBeNull();
  });

  it("counts code points, as the server does", () => {
    const stored = "\u{1F600} Total: $5";
    const reading = "Date: today\n\u{1F600} Total: $5";
    const segments: TextSegment[] = [{ stored_start: 0, reading_start: 12, length: 12 }];
    const span = mapSpanToReading({ start: 2, end: 7 }, segments, reading);
    expect(span).toEqual({ start: 14, end: 19 });
    expect(Array.from(stored).slice(2, 7).join("")).toBe("Total");
  });
});

describe("mapSpansToReading", () => {
  it("keeps each highlight that lands somewhere", () => {
    const a = STORED.indexOf("SEQ-0207");
    const spans = mapSpansToReading([{ start: a, end: a + 8 }], SEGMENTS, READING);
    expect(spans.map((s) => READING.slice(s.start, s.end))).toEqual(["SEQ-0207"]);
  });
});

// Real reading_view output from the backend (generated by the PR 185 review):
// four emails (LF and CRLF, Received or From first), with ranges inside kept
// spans, inside the replaced Date and dropped headers, and across both.

interface ReadingCase {
  name: string;
  segments: TextSegment[];
  text: string;
  span: [number, number];
  expected: [number, number] | null;
  expected_text: string | null;
}

describe("mapSpanToReading on real reading_view output", () => {
  const cases = CASES as ReadingCase[];
  const dateLine = "Date: Wed, 04 Mar 2026 15:00:00 +0000";
  const codePoints = (text: string, s: { start: number; end: number } | null) =>
    s ? Array.from(text).slice(s.start, s.end).join("") : null;

  it.each(cases.map((c) => [c.name, c] as const))("%s", (name, c) => {
    const got = mapSpanToReading({ start: c.span[0], end: c.span[1] }, c.segments, c.text);
    if (name.includes("wholly in Received (dropped)")) {
      // Ruling 49: the dropped Received header shares a gap with the replaced
      // Date header, and the segments can't tell them apart.
      expect(codePoints(c.text, got)).toBe(dateLine);
      return;
    }
    expect(got ? [got.start, got.end] : null).toEqual(c.expected);
    expect(codePoints(c.text, got)).toBe(c.expected_text);
  });

  it("keeps the Date line when a citation runs from it into the next line", () => {
    const c = cases.find((x) => x.name === "LF received-first: agent cites Date line + next line (via stored_range)")!;
    const got = mapSpanToReading({ start: c.span[0], end: c.span[1] }, c.segments, c.text);
    expect(codePoints(c.text, got)).toBe(`${dateLine}\nFrom: Pat <pat@vendor.example>`);
  });

  it("highlights nothing for an empty range", () => {
    const c = cases[0];
    for (const at of [0, 10, c.span[0]]) expect(mapSpanToReading({ start: at, end: at }, c.segments, c.text)).toBeNull();
  });
});


describe("passageInReading (ruling 50: the passage is reading text, positions stay stored)", () => {
  // The Message-ID header is dropped before the cited lines, and Date is replaced.
  const stored = "Date: Sat, 21 Feb 2026 09:30:00 -0800\nMessage-ID: <synthetic-0001@university.example>\nContent-Type: text/plain\n\nTotal: $2,180.00\n";
  const reading = "Date: Fri, 10 Apr 2026 17:00:00 +0000\nContent-Type: text/plain\n\nTotal: $2,180.00\n";
  const keptAt = stored.indexOf("Content-Type");
  const segments: TextSegment[] = [
    { stored_start: keptAt, reading_start: reading.indexOf("Content-Type"), length: stored.length - keptAt },
  ];
  const marked = (passage: string, spans: { start: number; end: number }[], offset: number) =>
    splitBySpans(passage, spans, offset)
      .filter((p) => p.marked)
      .map((p) => p.text);

  it("marks a value after a dropped header in the right place", () => {
    // The passage runs from the Date line, across the dropped header, to the total.
    const passage = "Date: Fri, 10 Apr 2026 17:00:00 +0000\nContent-Type: text/plain\n\nTotal: $2,180.00";
    const value = stored.indexOf("$2,180.00");
    const { spans, offset } = passageInReading([{ start: value, end: value + 9 }], 0, segments, reading);
    expect(marked(passage, spans, offset)).toEqual(["$2,180.00"]);
    // Splitting by stored positions, as before, puts the mark in the wrong place.
    expect(marked(passage, [{ start: value, end: value + 9 }], 0)).not.toEqual(["$2,180.00"]);
  });

  it("marks the reading Date line for a highlight on the replaced Date header", () => {
    const passage = "Date: Fri, 10 Apr 2026 17:00:00 +0000\nContent-Type: text/plain";
    const at = stored.indexOf("Sat, 21 Feb 2026");
    const { spans, offset } = passageInReading([{ start: at, end: at + 16 }], 0, segments, reading);
    expect(offset).toBe(0);
    expect(marked(passage, spans, offset)).toEqual(["Date: Fri, 10 Apr 2026 17:00:00 +0000"]);
  });
});
